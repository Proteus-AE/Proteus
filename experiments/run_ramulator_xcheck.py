#!/usr/bin/env python3
"""Host-path cross-check against Ramulator 2.0.

The same physical-address stream (generated by pimcore_tracegen under the
unified xPU/PIM mapping) is executed twice:

  * by the built-in host-path model (FR-FCFS controller + bank timing state,
    pimcore_coexec --host-only), and
  * by Ramulator 2.0's cycle-accurate LPDDR5X model (ext/ramulator2).

Sequential and random patterns bound the row-hit and row-miss regimes.
Requires ext/ramulator2 (scripts/fetch_deps.sh); without it the experiment
reports the built-in side only and marks the external column SKIPPED.
"""
import os
import subprocess
import sys

from common import RESULTS, write_csv
from proteus_sim.dram import pimcore_bridge as pc
from proteus_sim.dram import ramulator_bridge as ram

PATTERNS = ["stream", "random"]
REQS = 200000
DURATION_US = 400.0


def tracegen(binary, pattern, style, out):
    subprocess.run([binary, "--host-stream", "--pattern", pattern,
                    "--reqs", str(REQS), "--style", style, "-o", out],
                   check=True, capture_output=True)


def builtin_host_bw(build_dir, pattern):
    exe = os.path.join(build_dir, "pimcore_coexec")
    proc = subprocess.run(
        [exe, "--host-only", "--pattern", pattern, "--offered", "20",
         "--duration-us", str(DURATION_US)],
        check=True, capture_output=True, text=True,
        cwd=build_dir)
    line = proc.stdout.strip().splitlines()[-1].split(",")
    return float(line[2]), float(line[3])   # GB/s, mean latency ns


def main():
    pc.build()
    build_dir = pc.BUILD_DIR
    tgen = os.path.join(build_dir, "pimcore_tracegen")

    try:
        ram.find_binary()
        have_ram = True
    except ram.RamulatorUnavailable as e:
        have_ram = False
        print(f"note: {e}")
        print("      reporting the built-in host path only\n")

    rows = []
    for pattern in PATTERNS:
        bw, lat = builtin_host_bw(build_dir, pattern)
        if have_ram:
            traces = {}
            for style in ("rw", "ldst"):
                path = os.path.join(RESULTS, f"host_{pattern}.{style}.trace")
                tracegen(tgen, pattern, style, path)
                traces[style] = path
            try:
                rep = ram.run_stream(traces)
                ext_bw = round(rep["bw_gbps"], 3)
                ext_id = f"{rep['impl']}/{rep['timing']}"
                dev = f"{abs(ext_bw - bw) / ext_bw * 100:.1f}%" if ext_bw \
                    else "n/a"
            except ram.RamulatorUnavailable as e:
                ext_bw, ext_id, dev = "FAILED", str(e)[:60], "n/a"
        else:
            ext_bw, ext_id, dev = "SKIPPED", "-", "n/a"
        rows.append([pattern, round(bw, 3), round(lat, 1),
                     ext_bw, ext_id, dev])
        print(f"{pattern:<8} built-in {bw:6.2f} GB/s/ch "
              f"(lat {lat:.0f} ns) | ramulator2 {ext_bw} ({ext_id}) "
              f"| deviation {dev}")

    write_csv(os.path.join(RESULTS, "ramulator_xcheck.csv"),
              ["pattern", "builtin_gbps", "builtin_lat_ns",
               "ramulator2_gbps", "ramulator2_config", "deviation"], rows)
    print(f"\nwrote {os.path.join(RESULTS, 'ramulator_xcheck.csv')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
